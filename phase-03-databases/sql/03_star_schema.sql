-- ============================================================================
-- 03 — THE STAR SCHEMA (the warehouse)
--
-- Dimensional modeling in four decisions:
--
-- 1. THE GRAIN: one row of fact_sales = ONE ORDER LINE.
--    The grain is declared first; dimensions must describe exactly that
--    grain. (Alternative grains: one row per order, one row per day-product.
--    Mixing grains in one fact table is how warehouses lie.)
--
-- 2. FACTS hold MEASURES — numbers you sum, average, count: quantity,
--    unit_price, discount, revenue. Plus foreign keys to dimensions.
--
-- 3. DIMENSIONS hold CONTEXT — the who/what/when/where you filter and
--    group by. Every dimension has a SURROGATE key (dense integers) that
--    is independent of the source system's IDs (natural keys stay as
--    ordinary columns for traceability).
--
-- 4. DENORMALIZE FOR READS: category is FLATTENED into dim_product instead
--    of a separate table (that separate table would make it a SNOWFLAKE).
--    Star = fewer joins on the hot path; if the hierarchy grows complicated,
--    snowflaking is the escape hatch — at the cost of joins.
--
-- Notice what is NOT here: no CHECK constraints forbidding history, no
-- normalized address table, no status dimension. Warehouses are optimized
-- for analytical reads, not for transactional writes.
-- ============================================================================

-- Roll everything back first so the builder can be re-run from scratch.
DROP TABLE IF EXISTS fact_returns;
DROP TABLE IF EXISTS fact_sales;
DROP TABLE IF EXISTS dim_date;
DROP TABLE IF EXISTS dim_customer;
DROP TABLE IF EXISTS dim_customer_scd;
DROP TABLE IF EXISTS dim_product;

-- Date dimension: one row per calendar day. In real warehouses this is
-- pre-built (10 years = 3,650 rows of pure convenience: holidays, fiscal
-- periods, is_weekend...). Ours is generated by the ETL.
CREATE TABLE dim_date (
    date_key     INTEGER PRIMARY KEY,   -- 20250131 — human-readable AND sortable
    full_date    TEXT    NOT NULL,
    year         INTEGER NOT NULL,
    quarter      INTEGER NOT NULL,
    month        INTEGER NOT NULL,
    month_name   TEXT    NOT NULL,
    day_of_month INTEGER NOT NULL,
    day_of_week  INTEGER NOT NULL,      -- 0 = Sunday (SQLite convention)
    day_name     TEXT    NOT NULL,
    is_weekend   INTEGER NOT NULL CHECK (is_weekend IN (0, 1))
);

CREATE TABLE dim_customer (
    customer_key INTEGER PRIMARY KEY,   -- surrogate key
    customer_id  INTEGER NOT NULL,      -- natural key from the source system
    full_name    TEXT    NOT NULL,
    email        TEXT    NOT NULL,
    city         TEXT,                  -- current default address only
    country      TEXT
);

CREATE TABLE dim_product (
    product_key INTEGER PRIMARY KEY,    -- surrogate key
    product_id  INTEGER NOT NULL,       -- natural key
    sku         TEXT    NOT NULL,
    name        TEXT    NOT NULL,
    category    TEXT    NOT NULL,       -- flattened from categories (star, not snowflake)
    list_price  REAL    NOT NULL
);

CREATE TABLE fact_sales (
    sales_key      INTEGER PRIMARY KEY,
    -- degenerate dimension: the order number, useful context with no attributes
    order_id       INTEGER NOT NULL,
    line_no        INTEGER NOT NULL,
    -- dimension keys
    date_key       INTEGER NOT NULL REFERENCES dim_date(date_key),
    customer_key   INTEGER NOT NULL REFERENCES dim_customer(customer_key),
    product_key    INTEGER NOT NULL REFERENCES dim_product(product_key),
    -- measures
    quantity       INTEGER NOT NULL,
    unit_price     REAL    NOT NULL,
    discount_pct   REAL    NOT NULL,
    gross_amount   REAL    NOT NULL,    -- quantity * unit_price
    discount_amount REAL   NOT NULL,    -- gross * discount_pct
    net_revenue    REAL    NOT NULL,    -- gross - discount
    -- context attribute (see docs/MODELING.md: this is a mini-SCD problem)
    order_status   TEXT    NOT NULL
);

-- ----------------------------------------------------------------------------
-- The two "closing the caveats" tables:
--
-- dim_customer_scd — SLOWLY CHANGING DIMENSION, TYPE 2:
--   instead of one row per customer (current address only), one row per
--   VERSION of the customer. Each version carries valid_from / valid_to
--   and an is_current flag; history survives. A customer who moved in
--   2025 has two rows: one for before, one for after.
--
-- fact_returns — returns at their own grain:
--   one row per RETURNED LINE: when it came back, how many units, how
--   much was refunded. Replaces the order_status hack for anything the
--   business asks about returns.
-- ----------------------------------------------------------------------------

CREATE TABLE dim_customer_scd (
    customer_key INTEGER PRIMARY KEY,   -- surrogate key FOR THIS VERSION
    customer_id  INTEGER NOT NULL,      -- natural key, constant across versions
    full_name    TEXT    NOT NULL,
    email        TEXT    NOT NULL,
    city         TEXT,
    country      TEXT,
    valid_from   TEXT    NOT NULL,      -- version became effective this date
    valid_to     TEXT,                  -- NULL while the version is current
    is_current   INTEGER NOT NULL CHECK (is_current IN (0, 1))
);

CREATE TABLE fact_returns (
    return_key    INTEGER PRIMARY KEY,
    order_id      INTEGER NOT NULL,
    line_no       INTEGER NOT NULL,
    -- the RETURN date, not the order date — that's the grain
    date_key      INTEGER NOT NULL REFERENCES dim_date(date_key),
    customer_key  INTEGER NOT NULL REFERENCES dim_customer(customer_key),
    product_key   INTEGER NOT NULL REFERENCES dim_product(product_key),
    -- measures
    quantity      INTEGER NOT NULL,     -- units returned
    refund_amount REAL    NOT NULL      -- money refunded
);